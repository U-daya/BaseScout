"""Pick two candidate base pads at every Earth analog site from real elevation data.

Uses the same 25 x 25 km window, 500 m grid and sampling as build_terrain.py, so the
pad slopes come from the data shown on the terrain comparison screen.

    python scripts/pick_pads.py <folder with the .hgt.gz tiles>

Writes src/padSites.js. At each site, Pad A is the gentlest cell in the western candidate
zone (the favourite) and Pad B is the cell in the eastern zone whose slope is closest to
4.5 degrees, a steeper backup. Both zones sit 2-6 km from the window centre, away from edges.
For each site the script also re-checks the median and 90th percentile slope against
public/terrain/sites.json, so the pads come from the same data as the comparison.
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

from build_terrain import SIZE, SPACING, hgt, sample

EARTH_RADIUS = 6371008.8


def tile_bounds(url):
    name = url.rsplit('/', 1)[1].split('.')[0]          # e.g. N38W111
    lat = int(name[1:3]) * (1 if name[0] == 'N' else -1)
    lon = int(name[4:7]) * (1 if name[3] == 'E' else -1)
    return name, lat, lon


def main():
    tiles = Path(sys.argv[1])
    root = Path(__file__).resolve().parents[1]
    sites = json.loads((root / 'public' / 'terrain' / 'sites.json').read_text(encoding='utf-8'))
    half = SIZE // 2
    rows = range(half - 6, half + 7)
    west = range(half - 12, half - 3)
    east = range(half + 4, half + 13)
    result = {}
    for site in sites:
        if site['planet'] != 'Earth':
            continue
        name, south, west_lon = tile_bounds(site['url'])
        heights = sample(hgt(tiles / f'{name}.hgt.gz'), site['lat'], site['lon'], south=south, west=west_lon)
        dy, dx = np.gradient(heights, SPACING)
        slopes = np.degrees(np.arctan(np.hypot(dx, dy)))
        interior = slopes[1:-1, 1:-1]
        check = (round(float(np.median(interior)), 2), round(float(np.percentile(interior, 90)), 2))
        assert check == (site['median'], site['p90']), f"{site['id']}: {check} != stored"
        def best(cols, score):
            return min(((r, c, float(slopes[r, c])) for r in rows for c in cols), key=lambda x: score(x[2]))
        pads = {}
        for pad, (r, c, s) in (('A', best(west, lambda s: s)), ('B', best(east, lambda s: abs(s - 4.5)))):
            north_m, east_m = (half - r) * SPACING, (c - half) * SPACING
            lat = site['lat'] + math.degrees(north_m / EARTH_RADIUS)
            lon = site['lon'] + math.degrees(east_m / (EARTH_RADIUS * math.cos(math.radians(site['lat']))))
            pads[pad] = dict(slope=round(s, 1), lat=round(lat, 4), lon=round(lon, 4), elevationM=round(float(heights[r, c])))
        result[site['id']] = dict(name=site['name'], pads=pads)
        print(site['id'], pads['A']['slope'], pads['B']['slope'])
    out = root / 'src' / 'padSites.js'
    out.write_text(
        '// Generated by scripts/pick_pads.py from each Earth analog\'s elevation window\n'
        '// (Mapzen Skadi / SRTM, 25 x 25 km, 500 m grid). Do not edit by hand.\n'
        f'export const padSites = {json.dumps(result, indent=2, ensure_ascii=False)};\n', encoding='utf-8')


if __name__ == '__main__':
    main()
